#include <iostream>
using namespace std;

int main() {
    int num1, num2, soma;

    // Entrada do usuário
    cout << "Digite o primeiro número: ";
    cin >> num1;
    cout << "Digite o segundo número: ";
    cin >> num2;

    // Cálculo
    soma = num1 + num2;

    // Saída
    cout << "A soma dos dois números é: " << soma << endl;

    return 0;
}